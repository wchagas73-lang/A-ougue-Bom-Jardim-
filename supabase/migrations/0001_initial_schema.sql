-- Acesso restrito a usuários autenticados vinculados à mesma loja.
create policy "store members read own store" on public.stores
for select to authenticated using (id = public.current_store_id());

create policy "members read profiles in own store" on public.profiles
for select to authenticated using (store_id = public.current_store_id());

create policy "owner manages profiles" on public.profiles
for all to authenticated
using (store_id = public.current_store_id() and public.current_role() = 'owner')
with check (store_id = public.current_store_id() and role in ('owner','employee','technical_admin'));

create policy "members read categories" on public.categories
for select to authenticated using (store_id = public.current_store_id());
create policy "owner manages categories" on public.categories
for all to authenticated using (store_id = public.current_store_id() and public.current_role() = 'owner')
with check (store_id = public.current_store_id() and public.current_role() = 'owner');

