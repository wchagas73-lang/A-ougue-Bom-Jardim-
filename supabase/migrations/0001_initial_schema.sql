create policy "operational roles read orders" on public.orders
for select to authenticated using (store_id = public.current_store_id());
create policy "operational roles update orders" on public.orders
for update to authenticated
using (store_id = public.current_store_id() and public.current_role() in ('owner','employee'))
with check (store_id = public.current_store_id() and public.current_role() in ('owner','employee'));
create policy "owner inserts orders" on public.orders
for insert to authenticated with check (store_id = public.current_store_id() and public.current_role() = 'owner');

create policy "members read order items" on public.order_items
for select to authenticated using (
  exists(select 1 from public.orders o where o.id = order_id and o.store_id = public.current_store_id())
);
create policy "owner manages order items" on public.order_items
for all to authenticated
using (exists(select 1 from public.orders o where o.id = order_id and o.store_id = public.current_store_id() and public.current_role() = 'owner'))
with check (exists(select 1 from public.orders o where o.id = order_id and o.store_id = public.current_store_id() and public.current_role() = 'owner'));

create policy "members read order events" on public.order_events
for select to authenticated using (
  exists(select 1 from public.orders o where o.id = order_id and o.store_id = public.current_store_id())
);
create policy "operational roles add events" on public.order_events
for insert to authenticated with check (
  public.current_role() in ('owner','employee') and
  exists(select 1 from public.orders o where o.id = order_id and o.store_id = public.current_store_id())
);

create policy "owner reads delivery settings" on public.delivery_settings
for select to authenticated using (store_id = public.current_store_id());
create policy "owner manages delivery settings" on public.delivery_settings
for all to authenticated using (store_id = public.current_store_id() and public.current_role() = 'owner')
with check (store_id = public.current_store_id() and public.current_role() = 'owner');

