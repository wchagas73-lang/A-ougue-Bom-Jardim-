for select to authenticated using (
  public.current_role() = 'owner' and
  exists(select 1 from public.orders o where o.id = order_id and o.store_id = public.current_store_id())
);
create policy "owner manages payments" on public.payments
for all to authenticated
using (public.current_role() = 'owner' and exists(select 1 from public.orders o where o.id = order_id and o.store_id = public.current_store_id()))
with check (public.current_role() = 'owner' and exists(select 1 from public.orders o where o.id = order_id and o.store_id = public.current_store_id()));

