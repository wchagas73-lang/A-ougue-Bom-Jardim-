create extension if not exists pgcrypto;

create table if not exists public.stores (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text unique not null,
  whatsapp text,
  created_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  store_id uuid not null references public.stores(id) on delete restrict,
  full_name text not null,
  role text not null check (role in ('owner','employee','technical_admin')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete cascade,
  name text not null,
  sort_order int not null default 0,
  active boolean not null default true,
  unique(store_id, name)
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete cascade,
  category_id uuid references public.categories(id) on delete set null,
  name text not null,
  description text,
  price numeric(10,2) not null check (price >= 0),
  unit text not null default 'kg' check (unit in ('kg','un.')),
  image_url text,
  active boolean not null default true,
  available boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.promotions (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete cascade,
  product_id uuid not null references public.products(id) on delete cascade,
  old_price numeric(10,2) not null check (old_price >= 0),
  promotional_price numeric(10,2) not null check (promotional_price >= 0),
  starts_at timestamptz,
  ends_at timestamptz,
  active boolean not null default true,
  check (promotional_price <= old_price)
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete restrict,
  order_number bigint generated by default as identity,
  customer_name text not null,
  customer_phone text not null,
  delivery_address text not null,
  payment_method text not null check (payment_method in ('pix','cash','debit','credit')),
  status text not null default 'received'
    check (status in ('received','preparing','out_for_delivery','delivered','cancelled','awaiting_resolution')),
  subtotal numeric(10,2) not null default 0 check (subtotal >= 0),
  delivery_fee numeric(10,2) not null default 0 check (delivery_fee >= 0),
  total numeric(10,2) not null default 0 check (total >= 0),
  customer_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(store_id, order_number)
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  quantity numeric(10,3) not null check (quantity > 0),
  unit text not null,
  unit_price numeric(10,2) not null check (unit_price >= 0),
  line_total numeric(10,2) not null check (line_total >= 0)
);

create table if not exists public.order_events (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  actor_id uuid references auth.users(id) on delete set null,
  event_type text not null,
  old_value text,
  new_value text,
  note text,
  created_at timestamptz not null default now()
);

create table if not exists public.delivery_settings (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null unique references public.stores(id) on delete cascade,
  mode text not null default 'fixed' check (mode in ('fixed','by_neighborhood','free_over','manual')),
  fixed_fee numeric(10,2) not null default 0 check (fixed_fee >= 0),
  free_over_amount numeric(10,2) check (free_over_amount >= 0),
  active boolean not null default true
);

create table if not exists public.payments (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  amount numeric(10,2) not null check (amount >= 0),
  method text not null check (method in ('pix','cash','debit','credit')),
  status text not null default 'pending' check (status in ('pending','received','refunded','failed')),
  received_at timestamptz,
  recorded_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create or replace function public.current_store_id()
returns uuid language sql stable security definer
set search_path = public
as $$
  select store_id from public.profiles
  where id = auth.uid() and active = true
  limit 1
$$;

create or replace function public.current_role()
returns text language sql stable security definer
set search_path = public
as $$
  select role from public.profiles
  where id = auth.uid() and active = true
  limit 1
$$;

